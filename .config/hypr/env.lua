-- Environment / desktop integration.
-- Note: the session is started by uwsm, which already exports the XDG_* session
-- variables to systemd; these are for processes Hyprland spawns.

-- Cursor: Bibata-Modern-Classic (as in end-4; AUR bibata-cursor-theme-bin, optional).
-- Missing theme → toolkits fall back to the default cursor.
hl.env("XCURSOR_THEME", "Bibata-Modern-Classic")
hl.env("XCURSOR_SIZE", "24")
hl.env("HYPRCURSOR_THEME", "Bibata-Modern-Classic")
hl.env("HYPRCURSOR_SIZE", "24")

-- Toolkits: prefer native Wayland, fall back to X11.
hl.env("QT_QPA_PLATFORM", "wayland;xcb")
-- Qt palette/icons/fonts from qt6ct (generated by scripts/theme.sh); without qt6ct installed Qt falls back to defaults
hl.env("QT_QPA_PLATFORMTHEME", "qt6ct")
hl.env("QT_WAYLAND_DISABLE_WINDOWDECORATION", "1")
hl.env("QT_AUTO_SCREEN_SCALE_FACTOR", "1")
-- Fractional monitor scale (1.25): without PassThrough, Qt rounds to an
-- integer internally, renders at that lower resolution, and the compositor
-- stretches the result back up — blurring every Qt6/Quickshell surface
-- (island, lock screen). SDDM's greeter already sets this; the session didn't.
hl.env("QT_SCALE_FACTOR_ROUNDING_POLICY", "PassThrough")
hl.env("GDK_BACKEND", "wayland,x11,*")
hl.env("SDL_VIDEODRIVER", "wayland,x11")
hl.env("CLUTTER_BACKEND", "wayland")
hl.env("ELECTRON_OZONE_PLATFORM_HINT", "auto")

hl.env("TERMINAL", "kitty")

-- KDE apps (Dolphin) outside Plasma: the Arch menu makes "Open with" work
-- (archlinux-xdg-menu); the colour scheme is written by scripts/theme.sh.
hl.env("XDG_MENU_PREFIX", "arch-")

-- Icon theme for Quickshell (island app icons) and Qt apps.
hl.env("QS_ICON_THEME", "Papirus-Dark")
