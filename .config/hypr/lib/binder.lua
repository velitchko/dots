-- Turns the keybinds.lua registry into real binds + the generated shortcuts views.

local safety = require("lib.safety")

local M = {}

local GROUP_ORDER = { "Apps", "Island", "Utilities", "Windows", "Workspaces", "Session", "Media" }

local function normalize(keys)
    return (keys:gsub("%s+", " "):upper())
end

local function dispatcher(e)
    if e.exec then return hl.dsp.exec_cmd(e.exec) end
    if e.dsp then return e.dsp() end
    error("bind '" .. e.keys .. "' has neither exec nor dsp")
end

local function grouped(binds)
    local groups, order, seen = {}, {}, {}
    for _, g in ipairs(GROUP_ORDER) do order[#order + 1] = g; seen[g] = true end
    for _, e in ipairs(binds) do
        if not e.hidden then
            if not seen[e.group] then order[#order + 1] = e.group; seen[e.group] = true end
            groups[e.group] = groups[e.group] or {}
            table.insert(groups[e.group], e)
        end
    end
    return groups, order
end

-- Key names → Nerd Font icons for the SUPER+/ list (codepoints checked by name
-- against Nerd Fonts' glyphnames.json). The Markdown view keeps plain names.
local ICON = {
    SUPER = "\u{f303}", SUPER_L = "\u{f303}",                       -- linux-archlinux
    SHIFT = "\u{f0636}", CTRL = "\u{f0634}", ALT = "\u{f0635}",      -- md-apple_keyboard_shift/control/option
    Return = "\u{f0311}", Tab = "\u{f0312}", Space = "\u{f1050}",    -- md-keyboard_return/tab/space
    Escape = "\u{f12b7}", Print = "\u{f0e51}",                       -- md-keyboard_esc, md-monitor_screenshot
    ["mouse:272"] = "\u{f037d} L", ["mouse:273"] = "\u{f037d} R", ["mouse:274"] = "\u{f037d} M",
    mouse_down = "\u{f1550}", mouse_up = "\u{f1551}",                -- md-mouse_move_down/up
    XF86AudioRaiseVolume = "\u{f057e}", XF86AudioLowerVolume = "\u{f057f}", XF86AudioMute = "\u{f075f}",
    XF86AudioMicMute = "\u{f036d}", XF86AudioPlay = "\u{f040e}", XF86AudioPause = "\u{f040e}",
    XF86AudioNext = "\u{f04ad}", XF86AudioPrev = "\u{f04ae}",
    XF86MonBrightnessUp = "\u{f00e0}", XF86MonBrightnessDown = "\u{f00de}",
    slash = "/", period = ".", equal = "=", minus = "\u{2212}", semicolon = ";", apostrophe = "'",
    left = "\u{2190}", right = "\u{2192}", Page_Up = "PgUp", Page_Down = "PgDn", Delete = "Del",
}
local function pretty_keys(keys)
    if keys == "SUPER + SUPER_L" then return "tap " .. ICON.SUPER end
    -- "SUPER (+ CTRL) + 1…0" style entries keep their wording, icons swapped in
    local s = keys:gsub("[%w_:]+", function(tok) return ICON[tok] or tok end)
    return (s:gsub(" %+ ", "  "))
end
local function pad(str, width)   -- pad by characters, not bytes (icons are multi-byte)
    local n = utf8.len(str) or #str
    return str .. string.rep(" ", math.max(1, width - n))
end

--- Plain-text view (for fuzzel --dmenu; shown with the Nerd Font Mono, so every
--- icon is one cell wide and the columns line up).
function M.render_text(binds)
    local groups, order = grouped(binds)
    local out = {}
    for _, g in ipairs(order) do
        for _, e in ipairs(groups[g] or {}) do
            out[#out + 1] = pad(g, 12) .. pad(pretty_keys(e.keys), 18) .. e.desc
        end
    end
    return table.concat(out, "\n") .. "\n"
end

--- Markdown view (docs/SHORTCUTS.md).
function M.render_markdown(binds)
    local groups, order = grouped(binds)
    local out = {
        "# Kessel shortcuts",
        "",
        "<!-- GENERATED by scripts/gen-shortcuts.sh from .config/hypr/keybinds.lua — do not edit by hand. -->",
        "",
    }
    for _, g in ipairs(order) do
        if groups[g] then
            out[#out + 1] = "## " .. g
            out[#out + 1] = ""
            out[#out + 1] = "| Keys | Action |"
            out[#out + 1] = "| --- | --- |"
            for _, e in ipairs(groups[g]) do
                out[#out + 1] = ("| `%s` | %s |"):format(e.keys, e.desc)
            end
            out[#out + 1] = ""
        end
    end
    return table.concat(out, "\n")
end

local function write(path, content)
    local f, err = io.open(path, "w")
    if not f then print("[kessel] cannot write " .. path .. ": " .. tostring(err)); return end
    f:write(content)
    f:close()
end

function M.apply(registry)
    if type(registry) ~= "table" or type(registry.binds) ~= "table" then
        -- e.g. Hyprland auto-reloaded while keybinds.lua was half-written; the next save fixes it
        error("keybinds.lua did not return { binds = … } (file mid-save?) — rescue binds active", 0)
    end
    local seen, errors = {}, {}
    for _, e in ipairs(registry.binds) do
        if not e.doc then
            local k = normalize(e.keys)
            if seen[k] then
                errors[#errors + 1] = ("duplicate bind %s (%s / %s)"):format(e.keys, seen[k], e.desc)
            else
                seen[k] = e.desc
                local opts = { description = e.desc }
                for ok_, v in pairs(e.opts or {}) do opts[ok_] = v end
                local ok, err = pcall(function() hl.bind(e.keys, dispatcher(e), opts) end)
                if ok then
                    safety.bound[e.keys] = true
                else
                    errors[#errors + 1] = ("%s: %s"):format(e.keys, tostring(err))
                end
            end
        end
    end

    local runtime = os.getenv("XDG_RUNTIME_DIR")
    if runtime then write(runtime .. "/kessel-shortcuts.txt", M.render_text(registry.binds)) end
    local md = os.getenv("KESSEL_SHORTCUTS_MD")
    if md then write(md, M.render_markdown(registry.binds)) end

    if #errors > 0 then error(table.concat(errors, "; "), 0) end
end

return M
